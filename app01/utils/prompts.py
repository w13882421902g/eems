"""
提示词模板（三段式：角色 + 任务 + 输出格式）

任务书要求掌握三段式写法：先给模型定"角色"，再讲清"要做什么"，最后约束"怎么输出"。
所有提示词集中在这里维护，便于答辩讲解和后续调整，视图层不拼接长段自然语言。
"""


# ===== T2 招聘 JD =====
JD_SYSTEM = "你是一名资深 HR，擅长撰写结构清晰、务实的招聘文案。"


def build_jd_prompt(title):
    """为指定岗位构造生成 JD 的提示词（角色在 system，任务与输出格式在 user）。"""
    return (
        f"请为「{title}」岗位撰写一份招聘 JD。\n"
        "必须包含以下三部分，并使用对应小标题分段：\n"
        "【岗位职责】列出 3-4 条主要工作内容；\n"
        "【任职要求】列出 3-4 条任职条件（学历、经验、技能等）；\n"
        "【薪资范围】给出一个合理的薪资区间。\n"
        "要求：使用简洁中文，全文约 150 字，不要出现与本岗位无关的内容。"
    )


# ===== T3 制度知识库问答 =====
QA_SYSTEM = (
    "你是一名企业制度助手。只能根据【资料】中提供的内容回答问题；"
    "资料中没有提及、或与资料无关的问题，必须直接回答'不知道'，不要编造规定、金额或流程。"
)


def build_qa_prompt(context, question):
    """把检索到的制度条目作为上下文注入，限定模型只照资料回答。"""
    return (
        f"【资料】\n{context}\n\n"
        f"【问题】\n{question}\n\n"
        "请结合上面的资料用简洁中文回答；若资料不足以回答，请回答'不知道'。"
    )


# ===== T4 数据智能点评 =====
COMMENT_SYSTEM = "你是一名客观中立的人事数据分析师，擅长基于考勤与薪资数据给出简短点评。"


def build_comment_prompt(data_text):
    """把结构化数据转成的可读文本注入，要求输出一句简短、客观的点评或建议。"""
    return (
        f"以下是某员工的考勤与薪资数据：\n{data_text}\n\n"
        "请基于这些数据，生成一句简短、客观的点评或改进建议（约 30-50 字），"
        "不要编造数据中没有的信息。"
    )


# ===== T5 多轮对话助手 =====
CHAT_SYSTEM = "你是一名企业内部智能助手，回答简洁、友好，围绕员工人事与办公相关问题。"


def build_chat_prompt(question, docs_text=""):
    """
    多轮对话提示词（对照参考仓库补强）：
    把制度检索结果作为【制度参考】注入，并明确“没有依据就说不知道”，
    避免模型在闲聊时顺手编造公司规定。
    """
    reference = docs_text.strip() or "（本次未检索到相关制度）"
    return (
        f"【制度参考】\n{reference}\n\n"
        f"【用户问题】\n{question.strip()}\n\n"
        "要求：结合最近几轮对话理解追问；涉及公司制度时只能依据【制度参考】作答，"
        "没有依据就回答“不知道”；回答控制在 300 字以内，需要分点时用 1. 2. 3. 编号。"
    )
